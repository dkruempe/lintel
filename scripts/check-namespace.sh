#!/usr/bin/env bash
#
# check-namespace.sh -- guard that public headers declare their own names only
# inside the `lintel` namespace.
#
# Rationale (A1 migration): the public API moved from the global C++ namespace
# into `lintel` (with nested `lintel::db`, `lintel::shm`, ...). A declaration
# that a later edit leaves at global scope silently reintroduces exactly the
# name collisions the migration removed, e.g. a consumer's own `Property` or
# `Result` clashing with lintel's. This check fails on any global-scope token
# that is not a namespace opening.
#
# Allowed at global scope: the `namespace lintel { ... }` block and known
# third-party forward-declaration blocks (`namespace spdlog {`, `namespace
# Hypodermic {`, `namespace httplib {`, ...). Everything else at that level is
# reported with file:line.
#
# Usage: ./scripts/check-namespace.sh [path]   (default: src/include/lintel)

set -euo pipefail

PROJ_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="${1:-$PROJ_ROOT/src/include/lintel}"

python3 - "$target" <<'PY'
import os
import re
import sys

root = sys.argv[1]

# `namespace name`, optional `{` on the same line; braces on the next line work too.
ns_re = re.compile(r'^namespace\s+[A-Za-z_][\w:]*\s*\{?\s*$')


def strip(code):
    """Blank out comments and string/char literals, preserving newlines."""
    out = []
    i, n = 0, len(code)
    while i < n:
        c = code[i]
        if c == '/' and i + 1 < n and code[i + 1] == '*':
            i += 2
            while i < n and not (code[i] == '*' and i + 1 < n and code[i + 1] == '/'):
                out.append('\n' if code[i] == '\n' else ' ')
                i += 1
            i += 2
            out.append('  ')
        elif c == '/' and i + 1 < n and code[i + 1] == '/':
            while i < n and code[i] != '\n':
                out.append(' ')
                i += 1
        elif c == '"' or c == "'":
            quote = c
            out.append(' ')
            i += 1
            while i < n and code[i] != quote:
                if code[i] == '\\' and i + 1 < n:
                    out.append(' ')
                    i += 2
                    continue
                out.append('\n' if code[i] == '\n' else ' ')
                i += 1
            if i < n:
                out.append(' ')
                i += 1
        else:
            out.append(c)
            i += 1
    return ''.join(out)


# `config.h` is generated by CMake from `config.h.in` and holds version macros
# plus the message-queue capacity constants; it is not part of the namespaced
# API surface and is deliberately not wrapped.
SKIP = {'config.h'}

problems = []
count = 0
for dirpath, _dirs, files in os.walk(root):
    for name in sorted(files):
        if not name.endswith('.h') or name in SKIP:
            continue
        path = os.path.join(dirpath, name)
        count += 1
        code = strip(open(path, encoding='utf-8', errors='replace').read())
        depth = 0
        continuation = False
        for lineno, line in enumerate(code.split('\n'), 1):
            stripped = line.strip()
            if continuation or stripped.startswith('#'):
                continuation = stripped.endswith('\\')
                continue
            if depth == 0 and stripped:
                if ns_re.match(stripped):
                    pass
                # one-line forward-declaration block, e.g. `namespace spdlog { class logger; }`
                elif stripped.startswith('namespace') and line.count('{') == line.count('}') and '{' in line:
                    pass
                else:
                    problems.append(f'{path}:{lineno}: {stripped}')
            depth += line.count('{') - line.count('}')
            if depth < 0:
                problems.append(f'{path}:{lineno}: unbalanced closing brace')
                depth = 0
        if depth != 0:
            problems.append(f'{path}: unbalanced braces (depth {depth})')

if problems:
    print('public headers declare names outside namespace lintel:', file=sys.stderr)
    for problem in problems:
        print('  ' + problem, file=sys.stderr)
    print(f'{len(problems)} problem(s) across {count} header(s)', file=sys.stderr)
    sys.exit(1)
print(f'namespace check passed ({count} headers)')
PY
